"""Build a private world draft without invoking the production art/release pipeline."""
import hashlib
import json
import shutil
import subprocess
import uuid
import argparse
from pathlib import Path

from bootstrap import EMERALD_REVISION, checkout, preserve_cleanup
from generate_world import ROOT, write_world
from host_toolchain import prepare_host, host_make
from maps import apply_maps
from engine_guards import apply_engine_guards
from world_native_audit import audit_native
from content_modules import MODULES, load_modules
from battle_content import apply_battles
from module_playtest import apply_playtest


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--modules-root', type=Path, default=MODULES,
                        help='Use an isolated package copy for native QA')
    parser.add_argument('--playtest-module', help='Build an explicitly isolated fresh-game module fixture')
    parser.add_argument('--scenario', choices=['ready', 'locked', 'completed', 'weak-party'], default='ready')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'romhack/world/world.json').read_text())
    directory = ROOT / 'romhack/content/world-blockout'
    modules = load_modules(manifest, args.modules_root)
    if args.playtest_module and args.playtest_module not in modules:
        parser.error('Unknown assigned playtest module')
    fixture = None
    def produce():
        nonlocal fixture
        plans, content = write_world(manifest, directory, args.modules_root)
        if args.playtest_module:
            fixture = apply_playtest(directory, content, modules, args.playtest_module, args.scenario)
        return plans, content
    plans, content = produce()
    # This independent validator owns no map generation or packing code.
    from world_contract import audit
    contract = audit(manifest, plans)
    if not contract['passed']:
        raise ValueError(json.dumps(contract, indent=2))
    before = {p.name: digest(p) for p in directory.iterdir() if p.is_file()}
    inputs = {'world.json': (ROOT / 'romhack/world/world.json').read_bytes()}
    for name in ('art-contract.json','districts.json'):
        inputs[name] = (ROOT/'romhack/world'/name).read_bytes()
    inputs.update({'generated/' + p.name: p.read_bytes() for p in directory.iterdir()
                   if p.is_file() and (p.name == 'content.json' or p.stem in
                                      {plan['world_id'] for plan in plans}
                                      or (p.name == 'module-battles.json' and 'battle_content' in content))})
    for path in args.modules_root.rglob('*'):
        if path.is_file():
            inputs['modules/' + str(path.relative_to(args.modules_root))] = path.read_bytes()
    produce()
    if before != {p.name: digest(p) for p in directory.iterdir() if p.is_file()}:
        raise ValueError('Regeneration changed generated bytes.')
    engine = prepare_host(ROOT / '.tools/pokeemerald-world-host')
    cache = {}
    previous = engine / 'sf-world-overlay.json'
    if previous.exists():
        # Optional package teams must not leak into the next default build.
        for relative in json.loads(previous.read_text()):
            if relative.startswith(('data/layouts/sf_world/','data/tilesets/secondary/sf_world_')):
                continue  # Generated files have no base revision; preserve them.
            path = engine / relative
            path.resolve().relative_to(engine.resolve())
            path.write_bytes(subprocess.check_output(
                ['git', 'show', EMERALD_REVISION + ':' + relative], cwd=engine))

    def original(path):
        if path not in cache:
            cache[path] = subprocess.check_output(
                ['git', 'show', EMERALD_REVISION + ':' + path], cwd=engine, text=True)
        return cache[path]

    ledger = []
    if manifest.get('town_finishing'):
        from world_tiles import compile_kit, apply_kit, describe
        profiles = {'residential'} | {p.get('tile_profile','residential') for p in plans}
        declared = json.loads((ROOT/'romhack/world/art-contract.json').read_text())['profiles']
        for profile in ['residential']+sorted(profiles-{'residential'}):
            kit = compile_kit(profile=profile)
            if describe(kit) != declared[profile]:
                raise ValueError('Review the changed native art allocation contract before building')
            ledger += apply_kit(engine, original, kit)
    ledger += apply_maps(content, ROOT, engine, original)
    ledger += apply_battles(content, ROOT, engine, original)
    ledger += apply_engine_guards(ROOT, engine, original)
    guard = engine / 'src/sf_save_guard.h'
    magic = fixture['save_magic'] if fixture else manifest['native']['save_magic']
    guard.write_text(guard.read_text().replace('0x5346', hex(magic)))
    for relative in ledger + ['src/sf_save_guard.h', 'src/sf_map_resume.h',
                               'src/sf_authored_maps.h', 'sf-host-build.json']:
        inputs['engine_overlay/' + relative] = (engine / relative).read_bytes()
    (engine / 'sf-world-overlay.json').write_text(json.dumps(ledger, indent=2) + '\n')
    name = 'sf-module-playtest' if fixture else manifest['native']['file_name']
    version = (f'0.0.81-module-playtest-{args.playtest_module}-{args.scenario}'
               if fixture else manifest['version'])
    inputs['build-mode.json'] = (json.dumps({'fixture': fixture}, sort_keys=True) + '\n').encode()
    host_make(engine, 'FILE_NAME=' + name, 'TITLE=' + ('SF MODULE QA' if fixture else 'SF WORLD TEST'),
              'GAME_CODE=' + manifest['native']['game_code'])
    target, elf = engine / (name + '.gba'), engine / (name + '.elf')
    native = audit_native(target, elf, plans, engine)
    if not native['passed']:
        raise ValueError(json.dumps(native, indent=2))
    output = ROOT / '.tools/romhack-drafts' / version / digest(target)
    output.mkdir(parents=True, exist_ok=True)
    run = output / 'receipts' / uuid.uuid4().hex
    run.mkdir(parents=True)
    for relative, data in inputs.items():
        path = run / 'inputs' / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists() and path.read_bytes() != data:
            raise ValueError('Frozen build input differs; preserve existing evidence.')
        if not path.exists():
            path.write_bytes(data)
    base = ROOT / '.tools/romhack-baseline/emerald-matching.gba'
    patch = run / 'candidate.bps'
    encoder = ROOT / '.tools/flips-macos'
    if not encoder.exists():
        flips = ROOT / '.tools/flips'
        checkout(flips, 'https://github.com/Alcaro/Flips.git',
                 'ff216a75df0987047a67d7923567dc4482ce07ac')
        preserve_cleanup(flips)
        host_make(flips, 'TARGET=cli', 'CFLAGS=-O2', 'FNAME_cli=' + str(encoder))
    subprocess.run([str(encoder), '--create', '--bps', '--exact', str(base),
                    str(target), str(patch)], check=True, timeout=300)
    roundtrip = run / 'roundtrip.gba'
    subprocess.run([str(encoder), '--apply', '--exact', str(patch), str(base),
                    str(roundtrip)], check=True, timeout=300)
    if roundtrip.read_bytes() != target.read_bytes():
        raise ValueError('Private patch roundtrip differs from compiled ROM.')
    canonical_patch = output / 'sf-world-blockout.bps'
    if canonical_patch.exists() and canonical_patch.read_bytes() != patch.read_bytes():
        raise ValueError('Frozen patch differs; preserve existing evidence.')
    if not canonical_patch.exists():
        shutil.copy2(patch, canonical_patch)
    for source, destination in ((target, 'target.gba'), (elf, 'target.elf')):
        dest = output / destination
        if dest.exists() and dest.read_bytes() != source.read_bytes():
            raise ValueError('Existing private evidence differs; preserve and inspect.')
        if not dest.exists():
            shutil.copy2(source, dest)
    receipt = {'version': version, 'profile': 'module-playtest' if fixture else manifest['profile'],
               'fixture': fixture,
               'target_sha256': digest(target), 'base_sha256': digest(base),
               'patch_sha256': digest(patch), 'patch_roundtrip': 'byte-identical',
               'save_magic': magic, 'save_schema': 1,
               'game_code': manifest['native']['game_code'],
               'emerald_revision': EMERALD_REVISION,
               'deterministic_generation': True, 'source_contract': contract,
               'compiled_maps': native, 'controller_traversal': 'pending',
               'web_traversal': 'pending', 'published': False,
               'frozen_inputs': {name: hashlib.sha256(data).hexdigest()
                                 for name, data in inputs.items()},
               'source_commit': subprocess.check_output(
                   ['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip()}
    receipt_bytes = (json.dumps(receipt, indent=2) + '\n').encode()
    (run / 'build.json').write_bytes(receipt_bytes)
    if not (output / 'manifest.json').exists():
        (output / 'manifest.json').write_bytes(receipt_bytes)
    print('Private draft: ' + str(output))
    print('Build receipt: ' + str(run / 'build.json'))
    print(json.dumps(native['counts']))


if __name__ == '__main__':
    main()
